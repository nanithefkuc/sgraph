    #[test]
    fn generation_replaces_prior_contents() {
        let generator = Rfc5053Triple::new(100).expect("K is in range");
        let mut out = NeighborBuf::<Binary>::new();
        generator
            .neighbors(CheckId::new(0), &mut out)
            .expect("generation is total over check ids");
        assert_eq!(support_of(&out), &[87, 32, 104, 49][..]);
        // Debris from an earlier check must not survive into the next one.
        generator
            .neighbors(CheckId::new(1), &mut out)
            .expect("generation is total over check ids");
        assert_eq!(support_of(&out), &[104, 51][..]);
    }

