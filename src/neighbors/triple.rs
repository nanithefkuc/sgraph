//! RFC 5053 Raptor LT neighbour selection.
//!
//! [`Rfc5053Triple`] is the LT stage of the Raptor code of RFC 5053: the
//! `(d, a, b)` triple generator of Section 5.4.4.4 walked by the `LTEnc`
//! neighbour rule of Section 5.4.4.3, expressed as a [`NeighborGen`] over the
//! intermediate-symbol domain.
//!
//! This is RFC 5053 Raptor and only that. RFC 6330 `RaptorQ` derives its
//! neighbours from a different, six-value tuple over a different domain; nothing
//! here implements or approximates it.
//!
//! Every derived quantity comes from `K`, the number of source symbols, by the
//! specification's own construction, and every step is integer arithmetic over
//! the two normative tables. The edge set is therefore identical on every
//! target.

use super::{NeighborBuf, NeighborGen};
use crate::error::GraphError;
use crate::id::{CheckId, VarId};
use crate::weight::{Binary, EdgeWeight};

/// The largest prime below `2^16`, the modulus of the triple generator's key
/// schedule (Section 5.4.4.4).
const Q: u32 = 65_521;

/// Size of the `Rand` domain the degree generator reads, `2^20`
/// (Section 5.4.4.2).
const DEGREE_DOMAIN: u32 = 1 << 20;

/// The breakpoints `f[0], ..., f[7]` of the degree table (Section 5.4.4.2).
const DEG_F: [u32; 8] = [
    0, 10_241, 491_582, 712_794, 831_695, 948_446, 1_032_189, 1_048_576,
];

/// The degrees `d[j]` paired with [`DEG_F`]. The table's index `j` runs from 1,
/// so `d[0]` is never read.
const DEG_D: [u32; 8] = [0, 1, 2, 3, 4, 10, 11, 40];

/// Largest degree the table of Section 5.4.4.2 can return.
const MAX_TABLE_DEGREE: u32 = 40;

/// Upper bound on the search for `H`.
///
/// `choose(16, 8) = 12870` already exceeds `K + S` for every admissible `K`, so
/// the search settles far below this; the bound only keeps the loop total.
const MAX_HALF_SEARCH: u32 = 32;

/// `Rand[X, i, m]` of Section 5.4.4.1.
///
/// `m` must be positive; every call site derives it from a prime or from
/// [`DEGREE_DOMAIN`].
#[inline]
fn rand(x: u32, i: u32, m: u32) -> u32 {
    let x = u64::from(x);
    let i = u64::from(i);
    let v0 = V0[((x + i) % 256) as usize];
    let v1 = V1[((x / 256 + i) % 256) as usize];
    (v0 ^ v1) % m
}

/// `Deg[v]` of Section 5.4.4.2, for `v < 2^20`.
///
/// Walks to the index `j` with `f[j-1] <= v < f[j]`. The final interval is
/// open-ended in the same sense the table is: `v` is bounded by `f[7]`, so
/// stopping the walk at `j == 7` returns `d[7]` rather than reading past the
/// table.
fn deg(v: u32) -> u32 {
    debug_assert!(v < DEGREE_DOMAIN);
    let mut j = 1;
    while j < 7 && v >= DEG_F[j] {
        j += 1;
    }
    DEG_D[j]
}

/// True when `n` is prime.
fn is_prime(n: u32) -> bool {
    if n < 2 {
        return false;
    }
    let mut d = 2u64;
    let n64 = u64::from(n);
    while d * d <= n64 {
        if n64 % d == 0 {
            return false;
        }
        d += 1;
    }
    true
}

/// The smallest prime that is at least `n`.
fn prime_at_least(n: u32) -> u32 {
    let mut p = if n < 2 { 2 } else { n };
    while !is_prime(p) {
        p += 1;
    }
    p
}

/// `choose(n, k)` for the small `n` the `H` search uses.
///
/// Exact at every step: `choose(n, i+1) = choose(n, i) * (n-i) / (i+1)` and the
/// product is always divisible by `i+1`.
fn binomial(n: u32, k: u32) -> u64 {
    debug_assert!(k <= n && n <= MAX_HALF_SEARCH);
    let k = if k > n - k { n - k } else { k };
    let mut acc = 1u64;
    let mut i = 0u32;
    while i < k {
        acc = acc * u64::from(n - i) / u64::from(i + 1);
        i += 1;
    }
    acc
}

/// The `S` LDPC symbols and `H` Half symbols that Section 5.4.2.3 derives from
/// `K`.
fn precode_counts(k: u32) -> (u32, u32) {
    // X: the smallest positive integer with X*(X-1) >= 2*K.
    let twice = 2 * u64::from(k);
    let mut x = 1u64;
    while x * (x - 1) < twice {
        x += 1;
    }
    // S: the smallest prime with S >= ceil(0.01*K) + X.
    let s = prime_at_least((u64::from(k).div_ceil(100) + x) as u32);
    // H: the smallest integer with choose(H, ceil(H/2)) >= K + S.
    let target = u64::from(k) + u64::from(s);
    let mut h = 1u32;
    while h < MAX_HALF_SEARCH && binomial(h, h.div_ceil(2)) < target {
        h += 1;
    }
    (s, h)
}

/// RFC 5053 Raptor LT neighbours over the intermediate-symbol domain.
///
/// The check id is the specification's encoding symbol ID `X`, and the variables
/// are indices into the `L` intermediate symbols `C[0], ..., C[L-1]`. Feeding
/// `X = 0, ..., K-1` reproduces the source symbol triples of Section 5.4.2.2,
/// which is how a consumer builds the `G_LT` rows of the pre-coding matrix;
/// larger `X` are repair symbols.
///
/// Only the LT stage lives here. The LDPC and Half relationships of
/// Section 5.4.2.3 constrain intermediate symbols to each other rather than
/// generating them from a check id, so they are the consumer's to assemble;
/// [`ldpc_count`](Rfc5053Triple::ldpc_count) and
/// [`half_count`](Rfc5053Triple::half_count) report how many of each the domain
/// ends with.
///
/// The triple generator's key schedule reduces `X` modulo
/// `Q = 65521`, so ids congruent modulo `Q` share a triple. That is the
/// specification's own behaviour, not a limit of this implementation, and it is
/// why any [`CheckId`] is accepted.
#[derive(Debug, Clone)]
pub struct Rfc5053Triple {
    k: u32,
    s: u32,
    h: u32,
    l: u32,
    l_prime: u32,
    systematic_index: u32,
    a_key: u32,
    b_key: u32,
    max_degree: u32,
}

impl Rfc5053Triple {
    /// Smallest source-symbol count the specification covers.
    pub const MIN_SYMBOLS: u32 = 4;

    /// Largest source-symbol count the specification covers.
    pub const MAX_SYMBOLS: u32 = 8192;

    /// A generator for a source block of `k` source symbols.
    ///
    /// `k` is the specification's `K` — the number of source symbols in the
    /// source block — and not the size of the neighbour domain. The domain is
    /// the `L = K + S + H` intermediate symbols derived from `K` by
    /// Section 5.4.2.3; read it back with
    /// [`intermediate_count`](Rfc5053Triple::intermediate_count).
    ///
    /// # Errors
    ///
    /// [`GraphError::Rfc5053SymbolCountOutOfRange`] when `k` is outside
    /// `4..=8192`. The triple generator needs the systematic index `J(K)`, and
    /// Section 5.7 tabulates it for exactly those `K`; outside that range the
    /// specification defines no value, and picking one would silently break the
    /// full-rank property `J(K)` exists to guarantee.
    pub fn new(k: u32) -> Result<Self, GraphError> {
        if !(Self::MIN_SYMBOLS..=Self::MAX_SYMBOLS).contains(&k) {
            return Err(GraphError::Rfc5053SymbolCountOutOfRange {
                k,
                min: Self::MIN_SYMBOLS,
                max: Self::MAX_SYMBOLS,
            });
        }
        let (s, h) = precode_counts(k);
        let l = k + s + h;
        let l_prime = prime_at_least(l);
        let systematic_index = u32::from(SYSTEMATIC_INDEX[(k - Self::MIN_SYMBOLS) as usize]);
        Ok(Self {
            k,
            s,
            h,
            l,
            l_prime,
            systematic_index,
            a_key: (53_591 + systematic_index * 997) % Q,
            b_key: (10_267 * (systematic_index + 1)) % Q,
            // The walk takes min(d, L) neighbours, so a domain narrower than the
            // degree table caps the degree.
            max_degree: if MAX_TABLE_DEGREE < l {
                MAX_TABLE_DEGREE
            } else {
                l
            },
        })
    }

    /// The number of source symbols, `K`.
    #[inline]
    #[must_use]
    pub fn source_count(&self) -> u32 {
        self.k
    }

    /// The number of LDPC symbols, `S`.
    #[inline]
    #[must_use]
    pub fn ldpc_count(&self) -> u32 {
        self.s
    }

    /// The number of Half symbols, `H`.
    #[inline]
    #[must_use]
    pub fn half_count(&self) -> u32 {
        self.h
    }

    /// The number of intermediate symbols, `L = K + S + H`.
    ///
    /// Every variable this generator emits is below this.
    #[inline]
    #[must_use]
    pub fn intermediate_count(&self) -> u32 {
        self.l
    }

    /// The smallest prime at least `L`, the modulus the neighbour walk steps in.
    #[inline]
    #[must_use]
    pub fn prime_modulus(&self) -> u32 {
        self.l_prime
    }

    /// The systematic index `J(K)` of Section 5.7.
    #[inline]
    #[must_use]
    pub fn systematic_index(&self) -> u32 {
        self.systematic_index
    }

    /// `Trip[K, X]` of Section 5.4.4.4: the degree `d`, the step `a` in
    /// `1..L'`, and the starting position `b` in `0..L'`.
    ///
    /// The neighbours [`NeighborGen::neighbors`] emits are what the `LTEnc` walk
    /// of Section 5.4.4.3 visits from this triple, so a consumer assembling the
    /// pre-coding matrix can read the triple and the edges from one place.
    #[must_use]
    pub fn triple(&self, id: CheckId) -> (u32, u32, u32) {
        // (B + X*A) % Q is unchanged by reducing X first, which is what lets a
        // 64-bit id feed a 16-bit key schedule without a separate domain check.
        let esi = id.get() % u64::from(Q);
        let key = ((u64::from(self.b_key) + esi * u64::from(self.a_key)) % u64::from(Q)) as u32;
        // `Y` is the key; the three draws are `v` (fed to `Deg`), `a`, and `b`.
        (
            deg(rand(key, 0, DEGREE_DOMAIN)),
            1 + rand(key, 1, self.l_prime - 1),
            rand(key, 2, self.l_prime),
        )
    }
}

impl NeighborGen for Rfc5053Triple {
    type Weight = Binary;

    fn neighbors(&self, id: CheckId, out: &mut NeighborBuf<Binary>) -> Result<(), GraphError> {
        out.clear();
        let (d, a, mut b) = self.triple(id);
        // The walk of Section 5.4.4.3 takes C[b] and then min(d-1, L-1) further
        // steps, so it yields min(d, L) neighbours. Positions at or above L are
        // skipped: they belong to the prime padding of the modulus, not to the
        // domain.
        let count = if d < self.l { d } else { self.l };
        while b >= self.l {
            b = (b + a) % self.l_prime;
        }
        out.push(VarId::new(u64::from(b)), Binary::one());
        for _ in 1..count {
            b = (b + a) % self.l_prime;
            while b >= self.l {
                b = (b + a) % self.l_prime;
            }
            out.push(VarId::new(u64::from(b)), Binary::one());
        }
        // L' is prime and a is non-zero, so b walks a full cycle of distinct
        // residues; the count above stops it before it can wrap onto one twice.
        Ok(())
    }

    #[inline]
    fn max_degree(&self) -> u32 {
        self.max_degree
    }
}

