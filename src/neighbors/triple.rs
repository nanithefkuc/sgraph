    /// A second, deliberately literal translation of Section 5.4.4.1:
    ///
    /// ```text
    /// Rand[X, i, m] = (V0[(X + i) % 256] ^ V1[(floor(X/256) + i) % 256]) % m
    /// ```
    ///
    /// Written from the pseudocode rather than from [`rand`], so that agreement
    /// between the two is evidence about the specification and not about one
    /// implementation reading itself back.
    fn rand_reference(x: u32, i: u32, m: u32) -> u32 {
        let first = V0[usize::try_from((u64::from(x) + u64::from(i)) % 256).expect("under 256")];
        let floor_x_over_256 = x / 256;
        let second = V1[usize::try_from((u64::from(floor_x_over_256) + u64::from(i)) % 256)
            .expect("under 256")];
        (first ^ second) % m
    }

