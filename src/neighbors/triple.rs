    #[test]
    fn neighbours_are_distinct_in_domain_and_of_the_drawn_degree() {
        let mut out = NeighborBuf::<Binary>::new();
        for k in [4u32, 5, 6, 10, 37, 100, 1024, 8192] {
            let generator = Rfc5053Triple::new(k).expect("K is in range");
            let l = generator.intermediate_count();
            for x in 0..300u64 {
                let id = CheckId::new(x);
                let (d, _, _) = generator.triple(id);
                generator
                    .neighbors(id, &mut out)
                    .expect("generation is total over check ids");
                assert_eq!(out.len() as u32, d.min(l), "degree for K={k}, X={x}");
                assert!(out.len() as u32 <= generator.max_degree());
                assert!(!out.is_empty());
                for var in out.support() {
                    assert!(var.get() < u64::from(l), "K={k}, X={x}, var={var}");
                }
                // `Edges::new` is the crate's own duplicate and emptiness check.
                out.edges().expect("distinct, non-empty support");
            }
        }
    }

