    #[test]
    fn degree_is_clamped_to_the_intermediate_count() {
        let generator = Rfc5053Triple::new(4).expect("K is in range");
        assert_eq!(generator.intermediate_count(), 14);
        // Trip[4, 88] draws d = 40 from the table while L is only 14, so the walk
        // stops after L neighbours and covers the whole domain exactly once.
        assert_eq!(generator.triple(CheckId::new(88)), (40, 3, 12));
        let mut out = NeighborBuf::<Binary>::new();
        generator
            .neighbors(CheckId::new(88), &mut out)
            .expect("generation is total over check ids");
        assert_eq!(out.len(), 14);
        let mut seen = support_of(&out);
        seen.sort_unstable();
        assert_eq!(seen, (0..14u32).collect::<Vec<_>>());
    }

